"""Regenerates src/seo/imageSizes.ts: intrinsic width/height of every file in
public/images, so <img> tags can carry width/height and reserve their space
before the file loads (no layout shift). Run after adding photos:
    python scripts/gen-image-sizes.py
"""
import os, urllib.parse
from PIL import Image

root = os.path.join(os.path.dirname(__file__), '..', 'public', 'images')
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'seo', 'imageSizes.ts')
rows = []
for dirpath, _, files in os.walk(root):
    for f in sorted(files):
        if not f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')):
            continue
        full = os.path.join(dirpath, f)
        try:
            w, h = Image.open(full).size
        except Exception:
            continue
        rel = os.path.relpath(full, os.path.join(root, '..')).replace(os.sep, '/')
        url = '/' + urllib.parse.quote(rel, safe='/')
        rows.append((url, w, h))
rows.sort()
with open(out, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('// Generated by scripts/gen-image-sizes.py — do not edit by hand.\n')
    fh.write('export const IMAGE_SIZES: Record<string, [number, number]> = {\n')
    for url, w, h in rows:
        fh.write(f"  '{url}': [{w}, {h}],\n")
    fh.write('};\n\n')
    fh.write("""/** width/height attributes for a site image, so the browser reserves its box
 *  before the file arrives. Unknown sources (doctor-uploaded photos, remote
 *  avatars) fall back to the given default. */
export function imgDims(src: string | undefined, fallback: [number, number] = [800, 600]): { width: number; height: number } {
  const [width, height] = (src && IMAGE_SIZES[src]) || fallback;
  return { width, height };
}
""")
print(len(rows), 'images')
